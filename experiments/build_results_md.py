"""
Builds experiments/RESULTS.md from the v7 stage summaries (tables only, generated; do not edit by hand).

Stages: 3 load sweep (data/processed/load_sweep_v7.csv), 4 offline rule check (e3_offline_policies.csv),
5 reaction-delay pilot (e2_summary.csv, e2_frozen.yaml), 6 DQN v7 offline (e3_dqn_v7.csv),
7-8 main run (e4_latency.csv, e4_best_fixed.csv, e4_tests.csv, e4_tests_sensitivity.csv,
e4_segment_oracle.csv, e4_by_date.csv).

    python experiments/build_results_md.py
"""

from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parent.parent
EX = ROOT / "experiments"
OUT = EX / "RESULTS.md"


def md(df, floatfmt=None):
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            f = (floatfmt or {}).get(c, "{:.4g}")
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f.format(v))
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep] + rows)


def main():
    L = ["# v7 results (generated)", "",
         "Generated by `experiments/build_results_md.py` from the stage summaries. Report: "
         "`docs/report/final_report.html`. All latencies are for 200-token responses unless stated.", ""]

    sw = pd.read_csv(ROOT / "data/processed/load_sweep_v7.csv")
    t = sw.pivot_table(index="load_workers", columns="arm", values="decode_sec_per_token", aggfunc="median")
    arms = [a for a in ["threads_2", "threads_3", "balanced", "threads_4", "threads_6", "threads_10"] if a in t.columns]
    t = t[arms]
    t["best_arm"] = t.idxmin(axis=1)
    t = t.reset_index()
    L += ["## Stage 3: load sweep v7", "",
          f"Median decode s/token per busy-worker level and arm ({len(sw)} runs, `data/processed/load_sweep_v7.csv`).", "",
          md(t, {a: "{:.4f}" for a in arms}), ""]

    off = pd.read_csv(EX / "e3_offline_policies.csv")
    L += ["## Stage 4: rule_lookup and cores_heuristic offline (on the sweep)", "",
          "Regret in s/token vs the best arm at each load level (`experiments/e3_offline_policies.csv`).", "",
          md(off[["load_workers", "external_cpu_during", "best_arm", "rule_lookup_arm", "rule_lookup_regret_sec_per_token",
                  "cores_heuristic_arm", "cores_heuristic_regret_sec_per_token"]]), ""]

    e2 = pd.read_csv(EX / "e2_summary.csv")
    p = e2.pivot_table(index="condition", columns="scenario", values="mean_latency_s").round(2)
    fz = yaml.safe_load((EX / "e2_frozen.yaml").read_text(encoding="utf-8"))
    L += ["## Stage 5: reaction-delay pilot", "",
          f"Mean latency (s, n = 3 per cell) per rule configuration (`experiments/e2_summary.csv`). "
          f"Frozen: `{fz['winner']}` (interval {fz['decision_interval']}, patience {fz['patience']}).", "",
          md(p.reset_index(), {c: "{:.2f}" for c in p.columns}), ""]

    dq = pd.read_csv(EX / "e3_dqn_v7.csv")
    L += ["## Stage 6: DQN v7 offline (leave-one-prompt-out)", "", "`experiments/e3_dqn_v7.csv`", "", md(dq), ""]

    lat = pd.read_csv(EX / "e4_latency.csv").pivot_table(index="scenario", columns="condition", values="mean")
    L += ["## Stages 7-8: main run (450 runs, 10 prompts x 5 scenarios x 9 conditions)", "",
          "### Mean latency (s), n = 10 per cell", "", "`experiments/e4_latency.csv`", "",
          md(lat.reset_index(), {c: "{:.2f}" for c in lat.columns}), ""]
    bf = pd.read_csv(EX / "e4_best_fixed.csv")
    L += ["### rule_lookup vs best fixed arm per scenario (descriptive)", "", "`experiments/e4_best_fixed.csv`", "",
          md(bf, {"mean_rule_lookup_s": "{:.2f}", "mean_best_fixed_s": "{:.2f}", "mean_diff_s": "{:.2f}",
                  "mean_diff_percent": "{:.1f}"}), ""]
    for name, f in [("Pre-registered tests (paired t, Holm over 20)", "e4_tests.csv"),
                    ("Sensitivity: paging-flagged runs removed", "e4_tests_sensitivity.csv")]:
        ts = pd.read_csv(EX / f)
        cols = ["a", "b", "scenario", "n", "mean_diff_s", "mean_diff_percent", "ci95_low_s", "ci95_high_s",
                "p_t_holm", "p_wilcoxon", "significant_holm_0.05"]
        L += [f"### {name}", "", f"`experiments/{f}`", "",
              md(ts[cols], {"mean_diff_s": "{:.2f}", "mean_diff_percent": "{:.1f}", "ci95_low_s": "{:.2f}",
                            "ci95_high_s": "{:.2f}", "p_t_holm": "{:.4f}", "p_wilcoxon": "{:.4f}"}), ""]
    orc = pd.read_csv(EX / "e4_segment_oracle.csv")
    oc = ["scenario", "mean_segment_oracle_s", "mean_best_single_fixed_s"] + [c for c in orc.columns if c.endswith("_regret_vs_oracle_s")]
    L += ["### Segment-oracle regret (s)", "", "`experiments/e4_segment_oracle.csv`", "",
          md(orc[oc], {c: "{:.2f}" for c in oc[1:]}), ""]
    bd = pd.read_csv(EX / "e4_by_date.csv")
    L += ["### Fixed arms by session (13 Oct vs 18-19 Oct)", "", "`experiments/e4_by_date.csv`", "",
          md(bd, {"mean_decode_sec_per_token": "{:.4f}", "mean_external_cpu_during": "{:.2f}"}), ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
